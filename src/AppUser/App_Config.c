  // read data from flash 
  flash_read(TEST_FLASH_ADDRESS_START, Flash_RW_Buffer, TEST_BUFEER_SIZE);
	printf("FlashR:%08X,%d \r\n",TEST_FLASH_ADDRESS_START,TEST_BUFEER_SIZE);
